export function getInnovatorFounderSurfaceStaticTranslation(
  language: LanguageCode,
  source: string,
): string | undefined {
  const text = source.trim();
  const direct = dictionaries[language]?.[text];
  if (direct) return direct;

  const patterns = numberWords[language];
  if (!patterns) return undefined;

  let match = text.match(/^Includes (\d+) business plan coin(?:s)?$/);
  if (match) return patterns.includesCoins(match[1]);

  match = text.match(/^(\d+)-(\d+) page plan$/);
  if (match) return patterns.pageRange(match[1], match[2]);

  match = text.match(/^(\d+)\+ page plan$/);
  if (match) return patterns.pageMin(match[1]);

  match = text.match(/^Access to (\d+) tools$/);
  if (match) return patterns.accessTools(match[1]);

  return undefined;
}
