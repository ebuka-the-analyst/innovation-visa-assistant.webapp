export function getInnovatorFounderStaticTranslation(language: LanguageCode, source: string): string {
  const text = source.trim();
  if (!text || language === "en") return source;

  const deepStatic = getInnovatorFounderDeepStaticTranslation(language, text);
  if (deepStatic) return deepStatic;

  if (language === "zh" && ZH[text]) return ZH[text];
  if (language === "ja" && JA[text]) return JA[text];

  if (language === "ja") {
    const coins = text.match(/^Includes (\d+) business plan coin(s)?$/);
    if (coins) return `ビジネスプラン用コインを${coins[1]}枚含む`;
    const tools = text.match(/^Access to (\d+) tools$/);
    if (tools) return `${tools[1]}個のツールを利用可能`;
    const pages = text.match(/^(\d+)-(\d+) page plan$/);
    if (pages) return `${pages[1]}～${pages[2]}ページのプラン`;
    const minPages = text.match(/^(\d+)\+ page plan$/);
    if (minPages) return `${minPages[1]}ページ以上のプラン`;
  }

  const core = CORE[language];
  if (core?.[text]) return core[text];

  const t = getTranslation(language);
  const common: Record<string, string> = {
    "All Features": t.ukLanding.allFeatures,
    "Features": t.ukLanding.allFeatures,
    "Tools": t.ukLanding.tools,
    "Blog": t.ukLanding.blog,
    "Pricing": t.ukLanding.pricing,
    "FAQ": t.ukLanding.faq,
    "Sign In": t.ukLanding.signIn,
    "Get Started": t.ukLanding.getStarted,
    "Dashboard": t.ukLanding.dashboard,
    "Log Out": t.ukLanding.signOut
  };
  return common[text] || source;
}

