const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "../client/src");
const outFile = path.join(root, "lib/generated-ui-string-allowlist.ts");
const strings = new Set();

const EXCLUDED_PARTS = [
  "/country-catalogue-static/",
  "/innovator-founder-static-i18n.ts",
  "/innovator-founder-deep-static-i18n.ts",
  "/uk-catalogue-static-translations",
  "/translations.ts",
  "/generated-ui-string-allowlist.ts",
];

const commonSingleWords = new Set([
  "About","Back","Blog","Cancel","Close","Confirm","Continue","Dashboard","Delete",
  "Download","Edit","Email","Error","FAQ","Features","Help","Home","Loading",
  "Login","Logout","Next","Open","Previous","Pricing","Refresh","Reset","Retry",
  "Save","Search","Settings","Sign","Submit","Success","Support","Tools","Upload",
  "Verify","View","Welcome",
]);

function normalize(value) {
  return value
    .replace(/\\n/g, " ")
    .replace(/\\t/g, " ")
    .replace(/\\r/g, " ")
    .replace(/\\(["'\\])/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

function looksLikeTailwind(value) {
  const tokens = value.split(/\s+/).filter(Boolean);
  if (tokens.length < 3) return false;
  const utilityLike = tokens.filter(token =>
    /^(?:[a-z]+:)*(?:-?[a-z][a-z0-9]*)(?:-[a-z0-9.\[\]/%]+)+!?$/i.test(token) ||
    /^(?:flex|grid|block|inline|hidden|relative|absolute|fixed|sticky|container|truncate|italic|underline|uppercase|lowercase|capitalize|grow|shrink|border|shadow|ring|transition|transform)$/i.test(token)
  ).length;
  return utilityLike / tokens.length >= 0.6;
}

function add(raw) {
  if (!raw) return;
  const value = normalize(raw);
  if (value.length < 2 || value.length > 900) return;
  if (!/[A-Za-z]/.test(value)) return;
  if (/\$\{|<\/?[A-Za-z]|=>|\b(?:const|let|var|function|return|import|export)\b/.test(value)) return;
  if (/^(?:https?:|mailto:|tel:|\/|\.|#|@\/)/i.test(value)) return;
  if (/^(?:application|image|text|audio|video)\//i.test(value)) return;
  if (/\.(?:tsx?|jsx?|css|json|png|jpe?g|webp|svg|pdf|docx?|xlsx?|csv)$/i.test(value)) return;
  if (/^[A-Z0-9_]{3,}$/.test(value)) return;
  if (looksLikeTailwind(value)) return;

  const words = value.split(/\s+/);
  const startsLikeCopy = /^[A-Z0-9“"'(]/.test(value);
  const hasSentenceShape = words.length >= 2 && /[A-Za-z]/.test(value);
  const isCommonSingle = words.length === 1 && commonSingleWords.has(value);

  if (!startsLikeCopy && !hasSentenceShape && !isCommonSingle) return;
  strings.add(value);
}

function scan(file) {
  const source = fs.readFileSync(file, "utf8");

  // Human-readable JSX text.
  for (const match of source.matchAll(/>\s*([^<>{}][^<>{}]*)\s*</g)) add(match[1]);

  // Accessibility and form copy.
  for (const match of source.matchAll(/(?:placeholder|title|aria-label)\s*=\s*["']([^"']+)["']/g)) add(match[1]);

  // Common UI metadata fields.
  for (const match of source.matchAll(/(?:title|subtitle|description|label|heading|helperText|message|emptyText|buttonText|cta|name)\s*:\s*["']([^"']+)["']/g)) add(match[1]);

  // Sentence-like or title-like literals. This deliberately favours strings
  // beginning with capitals to avoid bundling route ids, CSS utilities and API keys.
  for (const match of source.matchAll(/(["'])([^"'\n]{2,900})\1/g)) {
    const value = match[2];
    if (/^[A-Z0-9“"'(]/.test(value) && (value.includes(" ") || commonSingleWords.has(value))) add(value);
  }
}

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const unix = full.replace(/\\/g, "/");
    if (EXCLUDED_PARTS.some(part => unix.includes(part))) continue;
    if (entry.isDirectory()) {
      walk(full);
    } else if (/\.(?:tsx?|jsx?)$/.test(entry.name)) {
      scan(full);
    }
  }
}

walk(root);

const values = Array.from(strings).sort((a,b) => a.localeCompare(b));
const body = `// Generated by scripts/generate-ui-string-allowlist.cjs. Do not edit manually.\nconst UI_STRINGS = new Set<string>(${JSON.stringify(values, null, 2)});\n\nexport function isKnownUiString(value: string): boolean {\n  return UI_STRINGS.has(value.trim());\n}\n\nexport const GENERATED_UI_STRING_COUNT = ${values.length};\n`;
fs.writeFileSync(outFile, body, "utf8");
console.log(`[i18n] generated ${values.length} UI source strings`);
